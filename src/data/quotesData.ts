export function getRandomQuote(excludeId?: string): PsychologicalQuote {
  const available = excludeId
    ? PSYCHOLOGICAL_QUOTES.filter((q) => q.id !== excludeId)
    : PSYCHOLOGICAL_QUOTES;
  const index = Math.floor(Math.random() * available.length);
  return available[index] || PSYCHOLOGICAL_QUOTES[0];
}
